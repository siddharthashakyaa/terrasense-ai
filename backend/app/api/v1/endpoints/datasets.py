from pathlib import Path
from typing import List
import uuid

import pandas as pd
from fastapi import APIRouter, Depends, UploadFile, File, HTTPException
from sqlalchemy.orm import Session

from app.core.config import settings
from app.db.database import get_db
from app.db import models as db_models
from app.ml.train import FEATURE_COLUMNS, TARGET_COLUMN
from app.ml.data_generator import save_synthetic_dataset
from app.schemas.schemas import DatasetOut, DatasetPreview

router = APIRouter()

REQUIRED_COLUMNS = FEATURE_COLUMNS + [TARGET_COLUMN]


def _validate_columns(df: pd.DataFrame) -> List[str]:
    messages = []
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        messages.append(f"Missing required columns: {', '.join(missing)}")
    if df.empty:
        messages.append("Dataset is empty.")
    numeric_cols = [c for c in FEATURE_COLUMNS if c in df.columns]
    for c in numeric_cols:
        if not pd.api.types.is_numeric_dtype(df[c]):
            messages.append(f"Column '{c}' must be numeric.")
    return messages


@router.get("/datasets", response_model=List[DatasetOut])
def list_datasets(db: Session = Depends(get_db)):
    rows = db.query(db_models.Dataset).order_by(db_models.Dataset.created_at.desc()).all()
    return [
        DatasetOut(
            id=r.id, filename=r.filename, source=r.source, row_count=r.row_count,
            column_count=r.column_count, columns=r.columns or [], is_synthetic=r.is_synthetic,
            notes=r.notes, created_at=r.created_at,
        ) for r in rows
    ]


@router.post("/datasets/upload", response_model=DatasetPreview)
async def upload_dataset(file: UploadFile = File(...), db: Session = Depends(get_db)):
    if not file.filename.lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Only .csv files are supported.")

    storage_dir = Path(settings.DATA_DIR) / "uploads"
    storage_dir.mkdir(parents=True, exist_ok=True)
    storage_path = storage_dir / f"{uuid.uuid4().hex}_{file.filename}"

    contents = await file.read()
    with open(storage_path, "wb") as f:
        f.write(contents)

    try:
        df = pd.read_csv(storage_path, comment="#")
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Could not parse CSV: {e}")

    validation_messages = _validate_columns(df)
    valid = len(validation_messages) == 0

    dataset = db_models.Dataset(
        filename=file.filename,
        source="upload",
        row_count=int(len(df)),
        column_count=int(len(df.columns)),
        columns=list(df.columns),
        storage_path=str(storage_path),
        is_synthetic=False,
        notes="User-uploaded dataset." if valid else "Uploaded dataset failed validation.",
    )
    db.add(dataset)
    db.commit()
    db.refresh(dataset)

    preview_rows = df.head(10).fillna("").to_dict(orient="records")

    return DatasetPreview(
        dataset=DatasetOut(
            id=dataset.id, filename=dataset.filename, source=dataset.source,
            row_count=dataset.row_count, column_count=dataset.column_count,
            columns=dataset.columns, is_synthetic=dataset.is_synthetic,
            notes=dataset.notes, created_at=dataset.created_at,
        ),
        preview_rows=preview_rows,
        valid_for_training=valid,
        validation_messages=validation_messages or ["Dataset looks valid and is ready for training."],
    )


@router.post("/datasets/synthetic", response_model=DatasetOut)
def generate_synthetic(db: Session = Depends(get_db), n_records: int = 6000):
    """Generate (or regenerate) the clearly-labeled synthetic/demo dataset."""
    path = save_synthetic_dataset(settings.SYNTHETIC_DATASET_PATH, n_records=n_records)
    df = pd.read_csv(path, comment="#")

    dataset = db_models.Dataset(
        filename=Path(path).name,
        source="synthetic",
        row_count=int(len(df)),
        column_count=int(len(df.columns)),
        columns=list(df.columns),
        storage_path=path,
        is_synthetic=True,
        notes="SYNTHETIC / DEMO dataset generated by TerraSense AI. Not real agricultural data.",
    )
    db.add(dataset)
    db.commit()
    db.refresh(dataset)

    return DatasetOut(
        id=dataset.id, filename=dataset.filename, source=dataset.source,
        row_count=dataset.row_count, column_count=dataset.column_count,
        columns=dataset.columns, is_synthetic=dataset.is_synthetic,
        notes=dataset.notes, created_at=dataset.created_at,
    )
